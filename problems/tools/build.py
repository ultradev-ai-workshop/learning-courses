"""Build problems.json, problems.js and tests/<ID>/NN.in|.out from the problem sources.

Run:  python3 tools/build.py      (from the problems folder or anywhere)
The reference solvers in src_*.py compute every expected output; they are never published.
"""
import json, os, shutil, sys, time
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import common
import src_easy, src_medium, src_hard, src_oop  # noqa: F401  (each registers its problems)
import src_oop_random  # noqa: F401  (adds a random stress script to every OOP problem)

MAX_SHOWN = 4000   # tests whose input or output is longer than this are only shipped as files


def run(p, text):
    start = time.perf_counter()
    result = p["solve"](text)
    took = time.perf_counter() - start
    if not isinstance(result, str) or not result.endswith("\n"):
        raise SystemExit(f"{p['id']}: solver must return text ending in a newline, got {result!r:.80}")
    if took > 5:
        print(f"  warning: {p['id']} solver took {took:.1f}s")
    return result


def build():
    seen, problems = set(), []
    for p in common.PROBLEMS:
        if p["id"] in seen:
            raise SystemExit(f"duplicate id {p['id']}")
        seen.add(p["id"])
        examples = [{"input": i, "output": run(p, i), "explanation": e} for i, e in p["examples"]]
        tests = [{"name": f"example {n}", "input": ex["input"], "output": ex["output"]} for n, ex in enumerate(examples, 1)]
        for n, i in enumerate(p["tests"], 1):
            tests.append({"name": f"test {n}", "input": i, "output": run(p, i)})
        if len({t["input"] for t in tests}) != len(tests):
            raise SystemExit(f"{p['id']}: duplicate test inputs")
        problems.append({k: p[k] for k in ("id", "title", "difficulty", "tags", "concepts", "statement", "input", "output", "constraints", "hints", "oop")}
                        | {"examples": examples, "tests": tests})

    tests_dir = os.path.join(ROOT, "tests")
    shutil.rmtree(tests_dir, ignore_errors=True)
    for p in problems:
        d = os.path.join(tests_dir, p["id"])
        os.makedirs(d)
        for n, t in enumerate(p["tests"], 1):
            with open(os.path.join(d, f"{n:02d}.in"), "w", newline="\n") as f: f.write(t["input"])
            with open(os.path.join(d, f"{n:02d}.out"), "w", newline="\n") as f: f.write(t["output"])
        for n, t in enumerate(p["tests"], 1):
            t["file"] = f"tests/{p['id']}/{n:02d}"
            t["large"] = len(t["input"]) > MAX_SHOWN or len(t["output"]) > MAX_SHOWN
            if t["large"]:   # keep the pages light: big tests are checked with the runner only
                t["size"] = {"input": len(t["input"]), "output": len(t["output"])}
                t["input"] = t["output"] = None

    data = json.dumps({"version": 1, "problems": problems}, ensure_ascii=False, indent=1)
    with open(os.path.join(ROOT, "problems.json"), "w") as f: f.write(data + "\n")
    with open(os.path.join(ROOT, "problems.js"), "w") as f:
        f.write("// Generated by tools/build.py — fallback for opening the pages from file:// (no fetch).\n")
        f.write("window.PROBLEM_SET = " + data + ";\n")

    by = Counter(p["difficulty"] for p in problems)
    print(f"{len(problems)} problems: " + ", ".join(f"{k}={v}" for k, v in sorted(by.items())))
    print(f"{sum(len(p['tests']) for p in problems)} tests, {sum(t['large'] for p in problems for t in p['tests'])} large; "
          f"problems.json {len(data) // 1024} KB")
    return problems


if __name__ == "__main__":
    build()
