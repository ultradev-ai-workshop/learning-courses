// Measures every course (prose words, example code lines, exercises, questions, problems) and writes
// the numbers plus a study-time estimate into index.html between the STATS markers.
// Usage: node tools/launcher-stats.mjs      (run after adding or changing a course)
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const COURSES = {
  python: "Beginner/python-book", react: "Beginner/react-book", javascript: "Intermediate/javascript-book",
  nodejs: "Intermediate/nodejs-book", aidev: "Intermediate/ai-dev-book", springboot: "Advanced/spring-boot-book", problems: "problems",
};
// Minutes per unit — the model explained on the launcher page.
export const MODEL = { wordsPerMinute: 180, minutesPerCodeLine: 1 / 6, exercise: { easy: 1.5, medium: 3.75, hard: 8.75 }, assessment: 50,
  problem: { easy: 15, medium: 30, hard: 60, oop: 45 },
  // per-course factor for the example time (Spring Boot examples are long but highly repetitive boilerplate)
  exampleFactor: { springboot: 0.25 } };

const strip = (html) => html.replace(/<script[\s\S]*?<\/script>/g, " ").replace(/<style[\s\S]*?<\/style>/g, " ")
  .replace(/<[^>]+>/g, " ").replace(/&[a-z#0-9]+;/gi, " ");
const words = (text) => (text.match(/[A-Za-z0-9À-ÿ'’-]+/g) || []).length;

function book(dir, id) {
  const pages = readdirSync(dir).filter((f) => /^(\d\d-|appendix-|howto-|playground-howto).*\.html$/.test(f) && f !== "howto-index.html");
  let prose = 0, code = 0, solutionCode = 0, ex = { easy: 0, medium: 0, hard: 0 }, chapters = 0, appendices = 0, howtos = 0;
  for (const f of pages) {
    const html = readFileSync(join(dir, f), "utf8");
    if (/^\d\d-/.test(f)) chapters++; else if (f.startsWith("appendix-")) appendices++; else if (f.startsWith("howto-")) howtos++;
    // code blocks outside and inside solutions
    const solutions = [...html.matchAll(/<details class="solution">[\s\S]*?<\/details>/g)].map((m) => m[0]).join("\n");
    const lines = (s) => [...s.matchAll(/<script type="text\/plain" class="code"[^>]*>([\s\S]*?)<\/script>/g)]
      .reduce((n, m) => n + m[1].split("\n").filter((l) => l.trim()).length, 0);
    const solLines = lines(solutions);
    code += lines(html) - solLines;
    solutionCode += solLines;
    prose += words(strip(html.replace(/<details class="solution">[\s\S]*?<\/details>/g, " ")));
    for (const m of html.matchAll(/class="lvl[^"]*">[^<]*?(easy|medium|hard)/g)) ex[m[1]]++;
  }
  const qfile = join(dir, "questions.json");
  const questions = existsSync(qfile) ? JSON.parse(readFileSync(qfile, "utf8")).questions.length : 0;
  const minutes = {
    reading: prose / MODEL.wordsPerMinute,
    examples: code * MODEL.minutesPerCodeLine * (MODEL.exampleFactor[id] ?? 1),
    exercises: ex.easy * MODEL.exercise.easy + ex.medium * MODEL.exercise.medium + ex.hard * MODEL.exercise.hard,
    assessment: questions ? MODEL.assessment : 0,
  };
  return { chapters, appendices, howtos, words: prose, codeLines: code, exercises: ex.easy + ex.medium + ex.hard, questions, minutes };
}

function problems(dir) {
  const data = JSON.parse(readFileSync(join(dir, "problems.json"), "utf8"));
  const list = Array.isArray(data) ? data : data.problems;
  const by = { easy: 0, medium: 0, hard: 0, oop: 0 };
  for (const p of list) {
    const d = String(p.category ?? p.difficulty ?? "").toLowerCase();
    by[/oop|object/.test(d) || /^O/.test(p.id ?? "") ? "oop" : d in by ? d : "medium"]++;
  }
  const tests = list.reduce((n, p) => n + (p.tests?.length ?? 0), 0);
  return { problems: list.length, byLevel: by, tests,
    minutes: { problems: by.easy * MODEL.problem.easy + by.medium * MODEL.problem.medium + by.hard * MODEL.problem.hard + by.oop * MODEL.problem.oop } };
}

const stats = {};
for (const [id, rel] of Object.entries(COURSES)) {
  const s = id === "problems" ? problems(join(ROOT, rel)) : book(join(ROOT, rel), id);
  const total = Object.values(s.minutes).reduce((a, b) => a + b, 0);
  s.minutes = Object.fromEntries(Object.entries(s.minutes).map(([k, v]) => [k, Math.round(v)]));
  s.hours = Math.max(1, Math.round(total / 60));
  stats[id] = s;
  console.log(`${id.padEnd(11)} ${String(s.hours).padStart(3)} h  ${JSON.stringify(s.minutes)}`);
}

const file = join(ROOT, "index.html");
const html = readFileSync(file, "utf8");
const block = `/* STATS:BEGIN — generated by tools/launcher-stats.mjs, do not edit by hand */\nvar MODEL = ${JSON.stringify(MODEL)};\nvar STATS = ${JSON.stringify(stats)};\n/* STATS:END */`;
if (!/\/\* STATS:BEGIN[\s\S]*?STATS:END \*\//.test(html)) throw new Error("index.html has no STATS markers");
writeFileSync(file, html.replace(/\/\* STATS:BEGIN[\s\S]*?STATS:END \*\//, block));
console.log("updated index.html");
