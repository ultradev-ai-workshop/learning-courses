// Build howto-index.html from the recipes in the howto-*.html pages (id, title, problem, tags).
// Usage: node tools/build-howto-index.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PAGES = [
  ["howto-config.html", "H1", "Application & Configuration", "⚙️"],
  ["howto-web.html", "H2", "Web & REST", "🌐"],
  ["howto-data.html", "H3", "Data Access", "🗄️"],
  ["howto-integration.html", "H4", "Integration & Background Work", "🔌"],
  ["howto-security.html", "H5", "Security", "🔐"],
  ["howto-testing-ops.html", "H6", "Testing & Operations", "🚀"],
];
const esc = (s) => s.replace(/&(?!\w+;|#\d+;)/g, "&amp;");
let total = 0;
const sections = PAGES.map(([file, code, title, icon]) => {
  const html = readFileSync(join(ROOT, file), "utf8");
  const recipes = [...html.matchAll(/<div class="recipe" id="([^"]+)">\s*<h2>([\s\S]*?)<\/h2>\s*<p class="problem">([\s\S]*?)<\/p>\s*<div class="tags">([\s\S]*?)<\/div>/g)]
    .map(([, id, h, problem, tags]) => ({ id, h, problem, tags: [...tags.matchAll(/<span>([\s\S]*?)<\/span>/g)].map((m) => m[1]) }));
  total += recipes.length;
  const items = recipes.map((r) => `  <a class="card" href="${file}#${r.id}"><div class="num">${code} · ${r.tags.slice(0, 2).join(" · ")}</div><h3>${r.h}</h3><p>${r.problem}</p></a>`).join("\n");
  return `<h2 id="${code.toLowerCase()}">${icon} ${code} · ${esc(title)}</h2>\n<div class="cards">\n${items}\n</div>`;
}).join("\n\n");

const page = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<link rel="icon" href="data:image/svg+xml,&lt;svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'&gt;&lt;text y='.9em' font-size='90'&gt;🍃&lt;/text&gt;&lt;/svg&gt;">
<title>How-To Guides · Spring Boot Study Book</title>
<link rel="stylesheet" href="book.css">
</head>
<body>
<div class="layout">
<nav id="sidebar"></nav>
<main class="content">

<!-- GENERATED by tools/build-howto-index.mjs from the howto-*.html pages. -->

<div class="eyebrow">How-To Guides</div>
<h1>How-To Guides</h1>
<p class="lead">${total} recipes for the tasks Spring Boot developers do most often. Each one states the problem, gives a solution you can copy (run and checked like every example in this book), and lists the pitfalls. The chapters explain the <em>why</em>; these pages get things done.</p>

<div class="tip">
<p>💡 <strong>How to read a recipe:</strong> <em>Problem</em> (the situation) → <em>Solution</em> (configuration and code, with real output) → <em>Pitfalls</em> (what goes wrong in production). The tags link each recipe to the chapter with the background.</p>
</div>

${sections}

<nav id="pager"></nav>
</main>
</div>
<script src="book.js"></script>
</body>
</html>
`;
writeFileSync(join(ROOT, "howto-index.html"), page);
console.log(`wrote howto-index.html (${total} recipes)`);
